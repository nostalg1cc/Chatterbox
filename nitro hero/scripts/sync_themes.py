"""Port Nitro's actual CSS theme variables and canonical preference IDs to Rust."""
import colorsys
import re
import sys
from pathlib import Path

hero = Path(__file__).resolve().parents[1]
repo = hero.parent
css = (repo / 'src/features/v3-shell/styles.css').read_text(encoding='utf-8')
options = (repo / 'src/lib/themes.ts').read_text(encoding='utf-8')
rows = re.findall(r'value: "([^"]+)", label: "([^"]+)"', options)
swatches = dict(re.findall(r'value: "([^"]+)"[^\n]+accent: "([^"]+)"', options))
assert len(rows) == 29

def rgb(value):
    if value.startswith('#'):
        return int(value[1:], 16)
    h, s, light = map(float, re.fullmatch(r'hsl\((\d+) (\d+)% (\d+)%\)', value).groups())
    r, g, b = colorsys.hls_to_rgb(h / 360, light / 100, s / 100)
    return (int(r * 255 + .5) << 16) | (int(g * 255 + .5) << 8) | int(b * 255 + .5)

def mix(a, b, amount):
    return sum(int(((a >> shift) & 255) * (1 - amount) + ((b >> shift) & 255) * amount + .5) << shift for shift in (16, 8, 0))

def luminance(color):
    channels = [((color >> shift) & 255) / 255 for shift in (16, 8, 0)]
    return sum(weight * (v / 12.92 if v <= .04045 else ((v + .055) / 1.055) ** 2.4) for weight, v in zip((.2126, .7152, .0722), channels))

def contrast(a, b):
    a, b = sorted((luminance(a), luminance(b)))
    return (b + .05) / (a + .05)

entries = []
for key, label in rows:
    variant = 'DefaultDark' if key == 'default' else key[0].upper() + key[1:]
    if key == 'default':
        bg = rgb(re.search(r'--app-bg:\s*(#[0-9a-fA-F]{6});', css)[1])
        material = rgb(re.search(r'--material-color:\s*(#[0-9a-fA-F]{6});', css)[1])
    else:
        body = re.search(r'\[data-theme="' + key + r'"\]\s*\{([^}]+)\}', css)[1]
        bg = rgb(re.search(r'--app-bg:\s*([^;]+)', body)[1])
        material = rgb(re.search(r'--material-color:\s*([^;]+)', body)[1])
    aliases = [variant]
    aliases += {'teal': ['Ocean'], 'lime': ['Moss'], 'sunset': ['Ember']}.get(key, [])
    track = mix(bg, 0, .42) if key != 'default' else 0x18181a
    raised = mix(material, 0xffffff, .12) if key != 'default' else 0x414147
    while contrast(0xd9d9d9, raised) < 4.6:
        raised = mix(raised, 0, .02)
    accent = rgb(swatches[key]) if key != 'default' else 0x0a84ff
    if key != 'default':
        while contrast(0xffffff, accent) < 4.6:
            accent = mix(accent, 0, .02)
    soft = rgb(swatches[key]) if key != 'default' else 0xa8d5ff
    while contrast(soft, raised) < 4.6:
        soft = mix(soft, 0xffffff, .03)
    line = rgb(swatches[key]) if key != 'default' else 0x6cb4ff
    while contrast(line, bg) < 3.2:
        line = mix(line, 0xffffff, .03)
    entries.append((key, label, variant, bg, material, aliases, accent, soft, line, track, raised))

lines = ['// Generated by scripts/sync_themes.py from Nitro CSS and THEME_OPTIONS.',
         '// Exact Nitro bg/material; custom accents and separated control surfaces for Hero.',
         'use serde::{Deserialize, Serialize};', 'use crate::state::Palette;',
         '#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]',
         'pub enum AppTheme {']
for key, label, variant, bg, material, aliases, *_ in entries:
    attrs = [f'rename = "{key}"'] + [f'alias = "{a}"' for a in aliases]
    lines += [f'    #[serde({", ".join(attrs)})]', f'    {variant},']
lines += ['}', 'impl AppTheme {', '    pub const ALL: [Self; 29] = [']
lines += [f'        Self::{v},' for _, _, v, *_ in entries]
lines += ['    ];', "    pub fn id(self) -> &'static str { match self {"]
lines += [f'        Self::{v} => "{key}",' for key, _, v, *_ in entries]
lines += ['    }}', "    pub fn label(self) -> &'static str { match self {"]
lines += [f'        Self::{v} => "{label}",' for _, label, v, *_ in entries]
lines += ['    }}', '    pub fn stage_bg(self) -> u32 { self.palette().stage }',
          '    pub fn bg_hex(self) -> u32 { self.stage_bg() }',
          '    pub fn preview_bar(self) -> u32 { self.palette().surface }',
          '    pub fn accent_dot(self) -> u32 { self.palette().accent }',
          '    pub const fn palette(self) -> Palette {', '        let (bg, material, accent, accent_soft, accent_line, subtle, raised) = match self {']
lines += [f'            Self::{v} => (' + ', '.join(f'0x{c:06x}' for c in (bg, material, accent, soft, line, track, raised)) + '),' for _, _, v, bg, material, _, accent, soft, line, track, raised in entries]
lines += ['        };', '        Palette {',
          '            canvas: bg, stage: bg, media: bg,',
          '            surface: material, subtle, panel: material, raised,',
          '            accent, accent_soft, accent_line,',
          '            text: 0xffffff, muted: 0xd9d9d9, selected: raised, hairline: material,',
          '        }', '    }', '}',
          '#[cfg(test)] mod tests { use super::*;',
          '    #[test] fn canonical_ids_round_trip_and_legacy_names_load() {',
          '        for theme in AppTheme::ALL {',
          '            let encoded = serde_json::to_string(&theme).unwrap();',
          '            assert_eq!(encoded, format!("\\\"{}\\\"", theme.id()));',
          '            assert_eq!(serde_json::from_str::<AppTheme>(&encoded).unwrap(), theme);',
          '        }',
          '        assert_eq!(serde_json::from_str::<AppTheme>("\\\"Ocean\\\"").unwrap(), AppTheme::Teal);',
          '        assert_eq!(serde_json::from_str::<AppTheme>("\\\"DefaultDark\\\"").unwrap(), AppTheme::DefaultDark);',
          '    }', '}']
generated = '\n'.join(lines) + '\n'
if '--check' in sys.argv:
    assert (hero / 'src/themes.rs').read_text(encoding='utf-8') == generated, 'Theme port differs from current Nitro sources; regenerate.'
    print('All 29 theme IDs and CSS palettes match the native port.')
    raise SystemExit(0)
(hero / 'src/themes.rs').write_text(generated, encoding='utf-8')
state_file = hero / 'src/state.rs'
state = state_file.read_text(encoding='utf-8')
start = state.find('#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]\npub enum AppTheme')
if start >= 0:
    end = state.index('/// The colour roles components draw with.', start)
    state = state[:start] + 'pub use crate::themes::AppTheme;\n\n' + state[end:]
    state_file.write_text(state, encoding='utf-8')
print('Synced 29 canonical IDs and exact CSS background/material colours.')
